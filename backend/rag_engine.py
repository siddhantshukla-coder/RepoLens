
from langgraph.graph import StateGraph, START, END
from langchain_groq import ChatGroq
from langchain_core.prompts import ChatPromptTemplate
from typing import TypedDict, Annotated, Literal
from langchain_core.documents import Document
from pydantic import BaseModel, Field
from dotenv import load_dotenv
from langchain_community.embeddings.fastembed import FastEmbedEmbeddings   # ONNX-based embeddings (no PyTorch, much less RAM)
from langchain_community.vectorstores import FAISS
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_core.output_parsers import StrOutputParser
from operator import add

load_dotenv()


# Same all-MiniLM-L6-v2 model as before (384-dim vectors), but run through ONNX Runtime via fastembed instead of
# PyTorch + sentence-transformers. This cuts memory use by several hundred MB, which is what let the app run out of RAM on Render's 512Mi tier.
embedding = FastEmbedEmbeddings(model_name="sentence-transformers/all-MiniLM-L6-v2")


retriever = None

llm = ChatGroq(model="openai/gpt-oss-20b")


# ====================== States and Structured outputs =========================

class State(TypedDict):
    question: str                         # the user's (possibly rewritten) question
    need_retrieval: bool                  # does this question need the docs at all?
    generated_answer: str                 # latest answer
    retrieved_documents: list[Document]   # raw chunks from the vector store
    relevant_retrieval: list[str]         # chunks that passed the relevance check
    is_supported: bool                    # is the answer grounded in the chunks?
    is_usable: bool                       # does the answer actually address the question?
    retry_count_use: int                  # how many times we rewrote the question
    retry_count_support: int              # how many times we revised an unsupported answer


class decide_retieval_temp(BaseModel):
    required_retrieval: bool = Field(description="Checks if the retrieval is need or not, depending on whether question is asking specifically from a citation, or source, which is provided then, True, otherwise False")
class relevant_retrieval_temp(BaseModel):
    required_relevant: bool = Field(description="True if the document covers the same code topic (file, function, module or concept) as the question, otherwise false")
class supported_response_temp(BaseModel):
    is_supported: bool = Field(description="Checks if the generated response is grounded according to the relevant retrieval documents")
class usable_response_temp(BaseModel):
    is_usable: bool = Field(description="Checks if the generated response is usable according to the question or not ")
class rewritten_question_template(BaseModel):
    rewritten_q: str = Field(description="If the answer generated by the model is not appropriate, then we reframe the question sent by the user.")


# ========================= LLM with structured output =========================
llm_with_decide_retrieval = llm.with_structured_output(
    decide_retieval_temp, method="json_mode"
)

llm_relevant_retrieval = llm.with_structured_output(
    relevant_retrieval_temp, method="json_mode"
)

llm_is_supported = llm.with_structured_output(
    supported_response_temp, method="json_mode"
)

llm_is_usable = llm.with_structured_output(
    usable_response_temp, method="json_mode"
)

llm_rewrite_question = llm.with_structured_output(
    rewritten_question_template, method="json_mode"
)


# ============================== Nodes Definitions =============================


def decide_retrieval(state: State):
    prompt = ChatPromptTemplate.from_messages([
        ("system",
            "Decide whether answering the question requires retrieving from the "
            "generated documentation of the user's code repository. Return your response strictly in JSON format. "
            "The JSON must contain the key required_retrieval with a boolean value.\n\n"
            "Default to required_retrieval=true.\n"
            "Return false ONLY for questions that clearly need no documents, such as:\n"
            "- greetings or small talk\n"
            "- requests to rewrite, translate, or reformat text the user already provided\n"
            "- questions about how you (the assistant) work\n\n"
            "Any question about the repository's code, files, functions, classes, architecture, "
            "setup, dependencies, logic, data flow or behaviour should return true, even if it "
            "seems like general programming knowledge, because the answer should follow the "
            "provided documentation.\n"
            "When unsure, return true."
        ),
        ("human", "Question:{question}")
    ]
    )
    chain = prompt | llm_with_decide_retrieval
    result: decide_retieval_temp = chain.invoke({'question': state['question']})
    return {'need_retrieval': result.required_retrieval}

def retrieve(state: State):
    result = retriever.invoke(state['question'])
    return {'retrieved_documents': result}

def generate_directly(state: State):
    prompt = ChatPromptTemplate.from_messages(
        [
            ("system", "You are a helpful assistant, which answers the users query from your own training data. Generate a well framed answer for the user's query and give a note in the end everytime:'This question was not related to the repository documentation though'."),
            ("human", "Answer this query: {query}")
        ]
    )
    chain = prompt | llm | StrOutputParser()
    result = chain.invoke({'query': state['question']})
    return {'generated_answer': result}

def is_relevant(state: State):
    prompt = ChatPromptTemplate.from_messages(
        [
            ("system", "You are judging document relevance at a TOPIC level.\n"
            "A documentation chunk is relevant if it discusses the same file, module, function, class or concept of the code repository as the question.\n"
            "Return your response strictly in JSON format. The JSON must contain the key required_relevant with a boolean value.\n"
            "It does NOT need to contain the exact answer.\n\n"
            "Do NOT decide whether the document fully answers the question. Return True if unsure.\n"
            "The document is: {document}"),
            ("human", "{question}")
        ]
    )
    question = state['question']
    chain = prompt | llm_relevant_retrieval
    final_list = []
    for doc in state['retrieved_documents']:
        each = chain.invoke({'question': question, 'document': doc.page_content})
        if each.required_relevant:
            final_list.append(doc.page_content)
    return {'relevant_retrieval': final_list}

def generate_from_content(state: State):
    relevant_retrieval = state['relevant_retrieval']
    question = state['question']
    prompt = ChatPromptTemplate.from_messages(
        [
            ("system", "You take in a question about a code repository and according to the question you generate the answer, properly grounded for the user from the relevant documentation excerpts selected for you, without using your own information. Mention file names, function names and class names wherever the excerpts provide them, and format the answer in Markdown (use code blocks for code). The relevant documentation excerpts are: {relevant_retrieval}"),
            ("human", "{question}")
        ]
    )
    chain = prompt | llm | StrOutputParser()
    result = chain.invoke({'question': question, 'relevant_retrieval': relevant_retrieval})
    return {'generated_answer': result}

def is_supported(state: State):
    generated_answer = state['generated_answer']
    relevant_retrieval = state['relevant_retrieval']
    prompt = ChatPromptTemplate.from_messages(
        [
            ('system', "You check if the generated response is generated purely with the use of the retrieved documentation or not. Return true or false accordingly. "
            "Return your response strictly in JSON format. The JSON must contain the key is_supported with a boolean value. "
            "Here is the generated answer and the relevant documentation excerpts: {generated_answer} and {relevant_retrieval}")
        ]
    )
    chain = prompt | llm_is_supported
    result = chain.invoke({'generated_answer': generated_answer, 'relevant_retrieval': relevant_retrieval})
    return {'is_supported': result.is_supported}

def revise_answer(state: State):
    relevant_retrieval = state['relevant_retrieval']
    question = state['question']
    prompt = ChatPromptTemplate.from_messages(
        [
            ("system", "The previous answer generated from the question taken previously, was either partially supported or not supported at all, ie it had facts which were not a part of the retrieved repository documentation. You need to generate answers strictly from the retrieved documentation or say Answer not found. Here are the relevant retrievals: {relevant_retrieval}"),
            ("human", "{question}")
        ]
    )
    chain = prompt | llm | StrOutputParser()
    result = chain.invoke({'question': question, 'relevant_retrieval': relevant_retrieval})
    return {'generated_answer': result, 'retry_count_support': state.get('retry_count_support', 0) + 1}

def is_usable(state: State):
    generated_answer = state['generated_answer']
    question = state['question']
    prompt = ChatPromptTemplate(
        [
            ('system', 'You are an agent which checks if the generated answer answers the question about the code repository correctly or not. If the answer matches the phrase answer not found, or it does not answer the question return False and other wise true. '
            'Return your response strictly in JSON format. The JSON must contain the key is_usable with a boolean value. '
            'Here is the generated answer: {generated_answer}'),
            ("human", "{question}")
        ]
    )
    chain = prompt | llm_is_usable
    result = chain.invoke({'generated_answer': generated_answer, 'question': question})
    return {'is_usable': result.is_usable}


def rewrite_question(state: State):
    prompt = ChatPromptTemplate.from_messages([
        ("system", "You are an assistant, which rewrites the user's question about a code repository into a more specific question (for example naming the likely file, function or concept involved) without changing its essence at all, so that we can get a more suitable answer from the repository documentation. "
        "Return your response strictly in JSON format. The JSON must contain the key rewritten_q with a string value."),
        ("human", "{question}")
    ])
    question = state['question']
    chain = prompt | llm_rewrite_question
    result = chain.invoke({'question': question})
    return {'question': result.rewritten_q,
            'retry_count_use': state.get('retry_count_use', 0) + 1}

def no_answer_found(state: State):
    return state


# ========================== Conditional Functions =============================


def if_retrieval_is_req(state: State) -> Literal['retrieve', 'generate_directly']:
    if state['need_retrieval']:
        return 'retrieve'
    else:
        return 'generate_directly'


def if_retrieved_are_rel(state: State) -> Literal['no_answer_found', 'generate_from_content']:
    if state['relevant_retrieval']:
        return 'generate_from_content'
    else:
        return 'no_answer_found'

def if_ans_supported(state: State) -> Literal['revise_answer', 'is_usable']:
    if state['is_supported']:
        return 'is_usable'
    elif state.get('retry_count_support', 0) >= 5:   # give up revising after 5 tries
        return 'is_usable'
    return 'revise_answer'

def if_ans_usable(state: State) -> Literal['rewrite_question', 'no_answer_found', '__end__']:
    if state['is_usable']:
        return END
    elif state.get("retry_count_use", 0) >= 5:       # give up rewriting after 5 tries
        return 'no_answer_found'
    return 'rewrite_question'


# ============================== Defining Graph ================================
graph = StateGraph(State)

# adding nodes
graph.add_node('decide_retrieval', decide_retrieval)
graph.add_node('retrieve', retrieve)
graph.add_node('is_relevant', is_relevant)
graph.add_node('generate_from_content', generate_from_content)
graph.add_node('is_supported', is_supported)
graph.add_node('revise_answer', revise_answer)
graph.add_node('is_usable', is_usable)
graph.add_node('rewrite_question', rewrite_question)
graph.add_node('no_answer_found', no_answer_found)
graph.add_node('generate_directly', generate_directly)

# adding edges
graph.add_edge(START, 'decide_retrieval')
graph.add_conditional_edges('decide_retrieval', if_retrieval_is_req)
graph.add_edge('generate_directly', END)
graph.add_edge('retrieve', 'is_relevant')
graph.add_conditional_edges('is_relevant', if_retrieved_are_rel)
graph.add_edge('generate_from_content', 'is_supported')
graph.add_conditional_edges('is_supported', if_ans_supported)
graph.add_edge('revise_answer', 'is_supported')
graph.add_conditional_edges('is_usable', if_ans_usable)
graph.add_edge('rewrite_question', 'retrieve')


self_rag = graph.compile()
